  const dictionaries = Object.fromEntries(locales.map((language, index) => [
    language,
    {
      ...Object.fromEntries(Object.entries(copy).map(([key, values]) => [key, values[index]])),
      ...window.PokemonTDUIStrings[language],
    },
  ]));

  function text(key, params = {}) {
    const template = dictionaries[locale][key];
    if (typeof template !== "string") throw new Error(`Missing Pokémon translation: ${locale}.${key}`);
    return template.replace(/\{(\w+)\}/g, (_, name) => {
      if (!(name in params)) throw new Error(`Missing Pokémon translation parameter: ${key}.${name}`);
      return String(params[name]);
    });
  }

  function pokemonName(id) {
    const pokemon = window.PokemonTDData.POKEMON[id];
    if (!pokemon) throw new Error(`Unknown Pokémon species: ${id}`);
    return pokemon[locale];
  }

  function applyDocument() {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "he" ? "rtl" : "ltr";
    for (const element of document.querySelectorAll("[data-i18n]")) {
      element.textContent = text(element.dataset.i18n);
    }
    for (const attribute of ["aria-label", "title"]) {
      for (const element of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
        element.setAttribute(attribute, text(element.getAttribute(`data-i18n-${attribute}`)));
      }
    }
  }

  window.PokemonTDLocale = { locale, text, pokemonName, applyDocument };
